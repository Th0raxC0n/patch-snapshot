import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const indexPath = path.join(root, "src", "index.mjs");
const keccakPath = path.join(root, "src", "keccak.mjs");
const outputDir = path.join(root, "dist");
const outputPath = path.join(outputDir, "patch-snapshot.mjs");

const indexSource = fs.readFileSync(indexPath, "utf8");
const keccakSource = fs.readFileSync(keccakPath, "utf8").trim();
const fsImport = 'import fs from "node:fs";';
const keccakImport = 'import { keccak256, keccakHex } from "./keccak.mjs";';

if (!indexSource.startsWith("#!/usr/bin/env node\n")) throw new Error("Unexpected src/index.mjs shebang");
if (!indexSource.includes(fsImport)) throw new Error("Expected node:fs import not found");
if (!indexSource.includes(keccakImport)) throw new Error("Expected keccak import not found");

const indexBody = indexSource
  .replace("#!/usr/bin/env node\n", "")
  .replace(`${fsImport}\n`, "")
  .replace(`${keccakImport}\n`, "")
  .trimStart();

const output = [
  "#!/usr/bin/env node",
  "",
  fsImport,
  "",
  "// Generated by scripts/build-standalone.mjs. Edit src/, not this file.",
  keccakSource,
  "",
  indexBody.trimEnd(),
  "",
].join("\n");

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputPath, output, { encoding: "utf8", mode: 0o755 });

const sha256 = crypto.createHash("sha256").update(output).digest("hex");
fs.writeFileSync(path.join(outputDir, "SHA256SUMS"), `${sha256}  patch-snapshot.mjs\n`, "utf8");

process.stdout.write(`built dist/patch-snapshot.mjs (${sha256})\n`);

